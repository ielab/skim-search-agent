"""The three analyses analysis.tex needs, computed from EXISTING per-episode rows only
(no new experiments, no GPU). Reads the six cells named in the task:

    FULL METHOD : runs/_headline_validation/agent/<ds>/Tongyi-DeepResearch-30B-A3B/agent_research_bql_dense_snip/rows.jsonl
    BASELINE    : runs/_visit_uncapped/agent/<ds>/Tongyi-DeepResearch-30B-A3B/agent_research_bm25/rows.jsonl
    ds in {browsecomp_plus_structured, hotpotqa_structured, musique_structured}

All six files are 188MB-750MB (well under the 17-31GB auto-read files the task says to avoid --
those are a different, unrelated set of conditions this script never touches).

REUSE, not reimplementation (per task instruction):
  - `scripts.force_answer_backfill.load_rows_with_recovery` for the recovery-overlaid
    `final_answer` (the SAME overlay `scripts/compare_cells.py`'s headline table uses).
  - `evaluation.metrics.answer_em` for the canonical EM.
  - `scripts.compare_cells.gold_doc_recall` for "did a gold corpus id surface in these
    observations" -- called TWICE per wrong row (once over ALL observations for retrieval
    failure, once over only the fetch/visit-typed observations for read/selection failure),
    using the row's own `actions`/`observations` parallel arrays (verified 1:1 aligned, 0
    mismatches, across all six cells) to split observations by tool type.

ANALYSIS 1 -- failure decomposition (retrieval / read-selection / synthesis), both cells,
    all 3 datasets (task asked for browsecomp at minimum, wiki "if time"; all three cost
    about the same to compute once the machinery is written, so all three are included).
ANALYSIS 2 -- query-operator adoption, full-method cell, all 3 datasets. This project's
    actual agent-facing query language is BQL v2 (`agent_search/prompts/skills/bql_*_v2.md`
    -- field-tagged `term[field]`, word-form `AND`/`OR`/`NOT`, typed `date[RANGE]`, wildcard
    `*`, quoted phrase; NEAR/proximity exists in the underlying grammar (docs/bql_spec.md)
    but is NOT taught in the v2 skill prompt these rows were produced under, and 0 uses were
    found by direct search -- see the "proximity" row). The task brief named generic Indri-
    style operator tokens (`#odN`/`#uwN`, `#date:`, `#less`/`#greater`/`#between`,
    `#weight`/`#combine`); this script maps each of those FUNCTIONAL categories onto this
    project's REAL surface syntax rather than grepping for tokens that don't occur in our
    data, and says so explicitly in the report.
ANALYSIS 3 -- cost accounting (count-once vs step-summed tokens, LLM calls), full method vs
    baseline, all 3 datasets.

OUTPUT: analysis/paper_analyses.md (tables + lift-able sentences) and this script's own
JSON sidecar analysis/paper_analyses_data.json (full numbers, for the writer / any figure
code later). Both regenerated by running this file.

    PYTHONPATH=. envs/bin/python analysis/paper_analyses.py
"""
