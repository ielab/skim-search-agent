# ANALYSIS 1 -- failure decomposition
# --------------------------------------------------------------------------------------

def _split_by_tool_type(row: dict) -> tuple:
    """(search-typed observations, fetch/visit-typed observations), using the row's own
    `actions` array (verified 1:1 aligned with `observations` -- 0 mismatches across all
    six cells checked directly). Action names vary by condition/typo-tolerance in the live
    loop (`bm25_search`/`search_bqlds`/`bm20_search`/... all contain "search"; `visit`/
    `fetch`/`fetch_bqlds`/`visit_bqlds` all contain "fetch" or "visit") -- matched by
    substring, case-insensitive, rather than an exact allow-list, so a typo'd tool name
    (real data: `bm20_search`, `bm2025_search`) still lands in the right bucket."""
    acts = row.get("actions") or []
    obs = row.get("observations") or []
    search_obs, fetch_obs = [], []
    if len(acts) == len(obs):
        for a, o in zip(acts, obs):
            al = (a or "").lower()
            if "search" in al:
                search_obs.append(o)
            elif "fetch" in al or "visit" in al:
                fetch_obs.append(o)
    else:  # defensive fallback (never hit on the six cells here; keeps this robust if reused)
        for o in obs:
            if o.startswith("search:"):
                search_obs.append(o)
            elif o.startswith("fetch:") or o.startswith("visit:"):
                fetch_obs.append(o)
    return search_obs, fetch_obs


def classify_row_failure(row: dict) -> str:
    """One of 'retrieval', 'selection', 'synthesis' for a WRONG (em==0) row.

    (a) retrieval  : gold_doc_recall over ALL observations is False -- no gold corpus id
                      ever surfaced anywhere (not even in a search-result listing).
    (b) selection   : a gold id surfaced somewhere (gold_doc_recall True over ALL obs) but
                      NEVER inside a fetch/visit-typed observation -- found, never opened.
    (c) synthesis   : a gold id appears in a fetch/visit-typed observation -- the agent DID
                      open/read the right document -- yet the final answer is still wrong.
                      (Sub-diagnostic, not a 4th bucket: whether the literal gold ANSWER
                      STRING also appears in the observations text -- the task's own test
                      for 'the agent read it but still got it wrong' -- is reported as a
                      within-category split, since a doc can be opened without the fetched
                      SLICE happening to contain the answer span, e.g. right doc/wrong
                      section -- still a synthesis-side failure, just a different flavor.)

    Uses gold_doc_recall (scripts/compare_cells.py) verbatim, called on synthetic
    {'observations': <subset>} dicts -- the function only reads that one key.
    """
    gold_ids = row.get("gold_ids") or set()
    search_obs, fetch_obs = _split_by_tool_type(row)
    all_obs = row.get("observations") or []
    if not gold_doc_recall({"observations": all_obs}, gold_ids):
        return "retrieval"
    if not gold_doc_recall({"observations": fetch_obs}, gold_ids):
        return "selection"
    return "synthesis"


def analysis1_for_cell(rows: list) -> dict:
    """Returns per-instance_id: {'em': bool, 'category': str|None (None if correct)}."""
    out = {}
    for r in rows:
        iid = r["instance_id"]
        gold = str(r.get("gold_answer") or "")
        ans = str(r.get("final_answer") or "")
        em = bool(answer_em(ans, gold))
        if em:
            out[iid] = {"em": True, "category": None}
            continue
        cat = classify_row_failure(r)
        gold_l = gold.lower().strip()
        surfaced = bool(gold_l) and gold_l in " ".join(r.get("observations") or []).lower()
        out[iid] = {"em": False, "category": cat, "surfaced": surfaced,
                     "question": r.get("question"), "gold_answer": gold,
                     "final_answer": ans, "n_gold_ids": len(r.get("gold_ids") or [])}
    return out


def summarize_categories(per_inst: dict) -> dict:
    wrong = [v for v in per_inst.values() if not v["em"]]
    n = len(wrong)
    if n == 0:
        return {"n_wrong": 0}
    counts = {"retrieval": 0, "selection": 0, "synthesis": 0}
    synth_surfaced = 0
    for v in wrong:
        counts[v["category"]] += 1
        if v["category"] == "synthesis" and v["surfaced"]:
            synth_surfaced += 1
    pct = {k: 100.0 * c / n for k, c in counts.items()}
    return {"n_wrong": n, "counts": counts, "pct": pct,
             "synthesis_answer_string_surfaced_pct": 100.0 * synth_surfaced / counts["synthesis"]
             if counts["synthesis"] else 0.0}


def flip_analysis(method_per_inst: dict, baseline_per_inst: dict) -> dict:
    """Instances the BASELINE got wrong that the METHOD got right -- classify by what
    failure mode the BASELINE had on exactly those instances. Answers 'where does the
    method's advantage come from'."""
    flips = []
    for iid, bv in baseline_per_inst.items():
        mv = method_per_inst.get(iid)
        if mv is None:
            continue
        if (not bv["em"]) and mv["em"]:
            flips.append((iid, bv["category"]))
    n = len(flips)
    counts = {"retrieval": 0, "selection": 0, "synthesis": 0}
    for _, cat in flips:
        counts[cat] += 1
    pct = {k: (100.0 * c / n if n else 0.0) for k, c in counts.items()}
    return {"n_flips": n, "counts": counts, "pct": pct}


# --------------------------------------------------------------------------------------
# ANALYSIS 2 -- query-operator adoption (full-method cell only)
# --------------------------------------------------------------------------------------

_SEARCH_ECHO_RE = re.compile(r"^search:\s*(.*?)\s+->\s+", re.DOTALL)
_FIELD_RE = re.compile(r"\[[a-zA-Z]+(?:\s*,\s*[a-zA-Z]+)*\]")   # term[field] / term[f1,f2]
_BOOL_RE = re.compile(r"\bAND\b|\bOR\b|\bNOT\b")                 # word-form (also matches AND(/OR(/NOT( )
_DATE_RE = re.compile(r"\bdate\[")
_NEAR_RE = re.compile(r"\bNEAR/")


def extract_queries(row: dict) -> list:
    out = []
    for o in row.get("observations") or []:
        if not o.startswith("search:"):
            continue
        m = _SEARCH_ECHO_RE.match(o)
        if m:
            out.append(m.group(1))
        else:  # malformed/truncated echo -- best-effort fallback, still counted
            out.append(o[len("search:"):].split("\n", 1)[0].strip())
    return out


def analysis2_for_cell(rows: list) -> dict:
    n = len(rows)
    flags = {"field": 0, "bool": 0, "proximity": 0, "date": 0, "multiclause": 0,
             "quoted": 0, "wildcard": 0, "bare_only": 0}
    example_field, example_date, example_multiclause = None, None, None
    n_queries_total = 0
    for r in rows:
        queries = extract_queries(r)
        n_queries_total += len(queries)
        has_field = any(_FIELD_RE.search(q) for q in queries)
        has_bool = any(_BOOL_RE.search(q) for q in queries)
        has_prox = any(_NEAR_RE.search(q) for q in queries)
        has_date = any(_DATE_RE.search(q) for q in queries)
        has_multi = any(len(_BOOL_RE.findall(q)) >= 2 for q in queries)
        has_quoted = any('"' in q for q in queries)
        has_wild = any("*" in q for q in queries)
        bare_only = len(queries) > 0 and not any(
            _FIELD_RE.search(q) or _BOOL_RE.search(q) or _DATE_RE.search(q) for q in queries)
        flags["field"] += has_field
        flags["bool"] += has_bool
        flags["proximity"] += has_prox
        flags["date"] += has_date
        flags["multiclause"] += has_multi
        flags["quoted"] += has_quoted
        flags["wildcard"] += has_wild
        flags["bare_only"] += bare_only
        if example_field is None:
            for q in queries:
                if _FIELD_RE.search(q):
                    example_field = q
                    break
        if example_date is None:
            for q in queries:
                if _DATE_RE.search(q):
                    example_date = q
                    break
        if example_multiclause is None:
            for q in queries:
                if len(_BOOL_RE.findall(q)) >= 2:
                    example_multiclause = q
                    break
    pct = {k: 100.0 * v / n for k, v in flags.items()} if n else {}
    return {"n_episodes": n, "n_queries_total": n_queries_total,
            "mean_queries_per_episode": n_queries_total / n if n else 0.0,
            "pct": pct,
            "examples": {"field_op": example_field, "date_op": example_date,
                         "multiclause": example_multiclause}}


