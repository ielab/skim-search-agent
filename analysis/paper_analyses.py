# ANALYSIS 3 -- cost accounting
# --------------------------------------------------------------------------------------

def analysis3_for_cell(rows: list) -> dict:
    n = len(rows)
    if n == 0:
        return {"n": 0}
    sum_once = sum_step_prompt = sum_step_compl = sum_calls = 0.0
    for r in rows:
        once = r.get("total_tokens_once")
        if once is None:
            once = ((r.get("initial_prompt_tokens") or 0) + (r.get("context_once_tokens") or 0)
                     + (r.get("output_tokens") or r.get("completion_tokens") or 0))
        sum_once += once
        sum_step_prompt += r.get("prompt_tokens") or 0
        sum_step_compl += r.get("completion_tokens") or 0
        sum_calls += r.get("llm_calls") or r.get("n_steps") or len(r.get("observations") or [])
    return {
        "n": n,
        "mean_tokens_once": sum_once / n,
        "mean_tokens_step_summed": (sum_step_prompt + sum_step_compl) / n,
        "mean_step_prompt_tokens": sum_step_prompt / n,
        "mean_step_completion_tokens": sum_step_compl / n,
        "mean_llm_calls": sum_calls / n,
    }


def pct_delta(method_v: float, baseline_v: float) -> float:
    if not baseline_v:
        return float("nan")
    return 100.0 * (method_v - baseline_v) / baseline_v


