def main():
    results = {"analysis1": {}, "analysis1_flips": {}, "analysis2": {}, "analysis3": {}}
    a1_per_inst = {}  # ds -> {"method":..., "baseline":...}

    for ds in DATASETS:
        print(f"[{ds}] loading method cell ...", file=sys.stderr)
        method_rows = load_cell(CELLS[ds]["method"])
        print(f"[{ds}] loading baseline cell ...", file=sys.stderr)
        baseline_rows = load_cell(CELLS[ds]["baseline"])

        print(f"[{ds}] analysis 1 ...", file=sys.stderr)
        m_per_inst = analysis1_for_cell(method_rows)
        b_per_inst = analysis1_for_cell(baseline_rows)
        a1_per_inst[ds] = {"method": m_per_inst, "baseline": b_per_inst}
        results["analysis1"][ds] = {
            "method": summarize_categories(m_per_inst),
            "baseline": summarize_categories(b_per_inst),
        }
        results["analysis1_flips"][ds] = flip_analysis(m_per_inst, b_per_inst)

        print(f"[{ds}] analysis 2 ...", file=sys.stderr)
        results["analysis2"][ds] = analysis2_for_cell(method_rows)

        print(f"[{ds}] analysis 3 ...", file=sys.stderr)
        results["analysis3"][ds] = {
            "method": analysis3_for_cell(method_rows),
            "baseline": analysis3_for_cell(baseline_rows),
        }
        results["analysis3"][ds]["delta_pct"] = {
            "tokens_once": pct_delta(results["analysis3"][ds]["method"]["mean_tokens_once"],
                                      results["analysis3"][ds]["baseline"]["mean_tokens_once"]),
            "tokens_step_summed": pct_delta(
                results["analysis3"][ds]["method"]["mean_tokens_step_summed"],
                results["analysis3"][ds]["baseline"]["mean_tokens_step_summed"]),
            "llm_calls": pct_delta(results["analysis3"][ds]["method"]["mean_llm_calls"],
                                    results["analysis3"][ds]["baseline"]["mean_llm_calls"]),
        }

        del method_rows, baseline_rows

    # ---- 5 hand-inspection examples (browsecomp method cell) for the report's sanity check
    hand_examples = []
    for iid, v in a1_per_inst["browsecomp_plus_structured"]["method"].items():
        if v["em"]:
            continue
        hand_examples.append((iid, v))
        if len(hand_examples) >= 5:
            break

    out_json = REPO_ROOT / "analysis" / "paper_analyses_data.json"
    with open(out_json, "w") as f:
        json.dump({"results": results,
                   "hand_examples": [{"instance_id": iid, **{k: v for k, v in rec.items()
                                       if k not in ("em",)}} for iid, rec in hand_examples]},
                  f, indent=2, default=str)
    print(f"wrote {out_json}", file=sys.stderr)

    write_markdown(results, hand_examples)


